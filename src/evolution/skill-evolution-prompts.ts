export function buildSkillAutoCreationPrompt(): string {
  return [
    '═══════════════════════════════════════════════════════════════',
    'SKILL AUTO-CREATION MODE',
    '═══════════════════════════════════════════════════════════════',
    '你刚完成了一个复杂任务，且没有使用任何已有 skill。',
    '',
    '分析这个工作流是否值得封装为新 skill：',
    '- 是否可能在未来类似任务中复用？',
    '- 是否有清晰的 输入 -> 处理 -> 输出 模式？',
    '- 封装后是否能节省 5 分钟以上？',
    '',
    '判定标准（全部满足才创建）：',
    '1. 可复用：不是一次性任务',
    '2. 定义清晰：步骤一致，非探索性对话',
    '3. 有价值：复用能省 5 分钟以上',
    '4. 可泛化：能参数化适配不同输入',
    '',
    '如果全部满足：',
    '-> 调用 skill-creator 工具，mode: "quick"，描述工作流步骤和预期输入输出。',
    '',
    '如果不满足：',
    '-> 回复"此任务不需要创建新 skill"。',
  ].join('\n')
}

export function buildSkillReflectionPrompt(skillName: string): string {
  return [
    '═══════════════════════════════════════════════════════════════',
    'SKILL REFLECTION MODE',
    '═══════════════════════════════════════════════════════════════',
    `你刚执行了 skill "${skillName}"。`,
    '',
    '快速分析这个 skill 是否可以改进：',
    '- 指令是否足够清晰？',
    '- 是否有未覆盖的边界情况？',
    '- 哪些步骤可以优化？',
    '- 是否缺少必要的上下文？',
    '- 执行结果是否符合预期？',
    '',
    '如果你发现了具体、可操作的改进点：',
    `-> 调用 skill-creator 工具，描述具体需要改进什么。`,
    '',
    '如果 skill 工作正常：',
    `-> 回复"Skill ${skillName} 工作正常，无需改进"。`,
    '',
    '约束：',
    '- 反思时间不超过 30 秒',
    '- 只建议有实质性改善的改进',
    '- 不确定就不改',
  ].join('\n')
}
